# Reads local image/video metadata without opening an editor or media player.
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$catalog=Get-Content -LiteralPath (Join-Path $root 'data/presentation/startup.json') -Raw | ConvertFrom-Json
Add-Type -AssemblyName System.Drawing
$records=@()
$shell=$null
try {
    foreach($asset in $catalog.assets){
        $absolute=[IO.Path]::GetFullPath((Join-Path $root $asset.path))
        $boundary=[IO.Path]::GetFullPath((Join-Path $root 'assets/runtime'))+[IO.Path]::DirectorySeparatorChar
        if(!$absolute.StartsWith($boundary,[StringComparison]::OrdinalIgnoreCase)){throw 'Inspection limited to project runtime assets'}
        if(!(Test-Path -LiteralPath $absolute -PathType Leaf)){continue}
        $file=Get-Item -LiteralPath $absolute
        $current=$absolute
        while($current.Length -gt $root.Length){
            if((Get-Item -LiteralPath $current -Force).Attributes -band [IO.FileAttributes]::ReparsePoint){throw 'Linked assets are not inspected'}
            $current=Split-Path $current -Parent
        }
        $r=[ordered]@{Id=$asset.id;Path=$asset.path;Bytes=$file.Length;Width=$null;Height=$null;DurationSeconds=$null;FramesPerSecond=$null;VideoCompressionIdentifier=$null;AudioChannels=$null;AudioSampleRate=$null;ImageDecodedForMetadata=$false;VideoPlayed=$false;VideoFramesDecoded=$false;DeclaredDimensionsMatch=$false}
        if($file.Extension.ToLowerInvariant() -in @('.png','.jpg','.jpeg')){
            $img=[Drawing.Image]::FromFile($absolute)
            try{$r.Width=$img.Width;$r.Height=$img.Height;$r.ImageDecodedForMetadata=$true}
            finally{$img.Dispose()}
        }elseif($file.Extension.ToLowerInvariant() -eq '.mp4'){
            if(!$shell){$shell=New-Object -ComObject Shell.Application}
            $folder=$null;$item=$null
            try{
                $folder=$shell.NameSpace($file.DirectoryName);$item=$folder.ParseName($file.Name)
                $r.Width=$item.ExtendedProperty('System.Video.FrameWidth')
                $r.Height=$item.ExtendedProperty('System.Video.FrameHeight')
                $duration=$item.ExtendedProperty('System.Media.Duration')
                $rate=$item.ExtendedProperty('System.Video.FrameRate')
                if($duration){$r.DurationSeconds=[double]$duration/10000000}
                if($rate){$r.FramesPerSecond=[double]$rate/1000}
                $r.VideoCompressionIdentifier=$item.ExtendedProperty('System.Video.Compression')
                $r.AudioChannels=$item.ExtendedProperty('System.Audio.ChannelCount')
                $r.AudioSampleRate=$item.ExtendedProperty('System.Audio.SampleRate')
            }finally{
                if($item){[void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($item)}
                if($folder){[void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($folder)}
            }
        }else{throw 'Unsupported local metadata inspection format'}
        if(!$r.Width -or !$r.Height){throw 'Dimensions unavailable; do not assume catalog values'}
        $r.DeclaredDimensionsMatch=($r.Width -eq $asset.width -and $r.Height -eq $asset.height)
        $records+=$r
    }
}finally{if($shell){[void][Runtime.InteropServices.Marshal]::FinalReleaseComObject($shell)}}
$report=[ordered]@{CheckedUtc=[DateTime]::UtcNow.ToString('o');Assets=$records;AllReceived=($records.Count -eq $catalog.assets.Count);CatalogDimensionsMatch=(@($records | Where-Object {!$_.DeclaredDimensionsMatch}).Count -eq 0);MetadataSource='System.Drawing images; Windows Shell extended media properties';EngineExecuted=$false;PlayerOpened=$false;NetworkAccessed=$false;Origin='User states all media created/generated by them';RightsIndependentlyAudited=$false;VideoPlaybackCompatibilityTested=$false}
$report | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath (Join-Path $root 'docs/relatorios/atuais/HUB-01A-RECURSOS.json') -Encoding utf8
$records | ForEach-Object {'MEDIA '+$_.Id+' '+$_.Width+'x'+$_.Height+' bytes='+$_.Bytes}
if(!$report.AllReceived -or !$report.CatalogDimensionsMatch){throw 'Receipt or catalog dimensions mismatch'}
